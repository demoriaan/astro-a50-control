_PLACEHOLDER = re.compile(r"\{(\w+)\}")


def pick_lang(env: Mapping[str, str]) -> str:
    """German if the message language is German. Like gettext, LANGUAGE only counts
    when a real locale is set; "C"/"POSIX" or no locale at all mean English."""
    locale_name = next((env[v] for v in ("LC_ALL", "LC_MESSAGES", "LANG") if env.get(v)), "")
    if locale_name.split(".")[0] in ("", "C", "POSIX"):
        return "en"
    language = env.get("LANGUAGE", "").split(":")[0].strip() or locale_name
    return "de" if language.lower().startswith("de") else "en"


LANG = pick_lang(os.environ)


def t(key: str, **values) -> str:
    text = STRINGS[LANG].get(key) or STRINGS["en"].get(key, key)
    return _PLACEHOLDER.sub(lambda m: str(values.get(m.group(1), "")), text)
